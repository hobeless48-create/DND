async (page) => {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const calls = [];
  const highlightName = `My first clue ${Date.now()}`;
  await page.route('**/api/status', route => route.fulfill({ json: { configured: true, model: 'fixture-no-paid-call' } }));
  await page.route('**/api/dm', async route => {
    const request = route.request().postDataJSON(); calls.push(request);
    const result = request.mode === 'summarize' ? { recap: 'The crew explored the Sealed Stair. The rescue choice remains unresolved.' } : request.mode === 'scene' ? { description: 'Water echoes against the old stone.' } : { kind: 'examine', reply: 'The stair remains quiet.' };
    await route.fulfill({ json: { result, usage: { inputTokens: 1, outputTokens: 1 } } });
  });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://127.0.0.1:5173/');
  await page.locator('#world-select').selectOption('fantasy');
  await page.getByRole('button', { name: 'New campaign', exact: true }).click();
  await page.locator('#hero-name').fill('Memory Tester');
  await page.locator('[data-start-skill]').nth(0).check(); await page.locator('[data-start-skill]').nth(2).check();
  await page.getByRole('button', { name: 'Add hero', exact: true }).click();
  await page.getByRole('button', { name: 'Begin expedition', exact: true }).click();
  await page.locator('#enter-dungeon').click();
  await page.locator('[data-inspector="story"]').click();
  await page.locator('.checkpoint-row').first().waitFor();
  await page.locator('#highlight-title').fill(highlightName);
  await page.locator('#save-highlight').click();
  const savedRow = page.locator('.checkpoint-row').filter({ hasText: highlightName });
  await savedRow.waitFor();
  const original = await page.evaluate(() => JSON.parse(localStorage.getItem('blackstone-campaign-v1')));
  await page.evaluate(() => {
    const state = JSON.parse(localStorage.getItem('blackstone-campaign-v1'));
    state.party[0].hp -= 5; state.gold = 900; state.storyFlags.futureChoice = true; state.rngState = (state.rngState + 123) >>> 0;
    localStorage.setItem('blackstone-campaign-v1', JSON.stringify(state));
  });
  await page.reload();
  await page.locator('[data-inspector="story"]').click();
  await savedRow.getByRole('button', { name: 'Resume scene', exact: true }).click();
  await page.waitForFunction(hp => JSON.parse(localStorage.getItem('blackstone-campaign-v1')).party[0].hp === hp, original.party[0].hp);
  const restored = await page.evaluate(() => JSON.parse(localStorage.getItem('blackstone-campaign-v1')));
  assert(restored.gold === original.gold && restored.rngState === original.rngState && !restored.storyFlags.futureChoice, 'Restore lost gold, RNG or choice state.');
  assert(JSON.stringify(restored.scene.tiles) === JSON.stringify(original.scene.tiles), 'Restore lost map tiles.');
  assert(await savedRow.count() === 1, 'A saved scene vanished after rewind.');
  // Populate a long story without paying for a thousand model requests.
  await page.evaluate(async () => {
    const { recordStoryEvent } = await import('/shared/story-memory.mjs');
    const state = JSON.parse(localStorage.getItem('blackstone-campaign-v1'));
    for (let i = 0; i < 1000; i++) recordStoryEvent(state, { id: `long-${i}`, type: 'story', text: `Past event ${i}: ${'The crew studied a quiet passage. '.repeat(8)}` });
    localStorage.setItem('blackstone-campaign-v1', JSON.stringify(state));
  });
  await page.reload();
  await page.locator('#command-input').fill('examine the room'); await page.locator('#command-send').click();
  await page.waitForFunction(() => !document.querySelector('#command-input').disabled);
  const intent = calls.findLast(call => call.mode === 'intent'), context = JSON.parse(intent.context);
  assert(context.storyMemory.recentEvents.length === 8, 'Prompt recent window was not bounded.');
  assert(context.storyMemory.recap.length <= 1800 && context.storyMemory.relevantHighlights.length <= 3, 'Recap or retrieval exceeded its allowance.');
  assert(intent.context.length < 15000 && !intent.context.includes('Past event 0:'), 'Growing transcript leaked into the prompt.');
  assert(!calls.some(call => call.mode === 'summarize'), 'AI recap was requested without the player clicking it.');
  await page.locator('[data-inspector="story"]').click();
  await page.locator('#refresh-recap').click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('blackstone-campaign-v1')).storyMemory.recapSource === 'ai');
  assert(calls.filter(call => call.mode === 'summarize').length === 1, 'Manual recap did not make exactly one request.');
  await page.reload(); await page.locator('[data-inspector="story"]').click();
  assert((await page.locator('#story-recap').textContent()).includes('choice remains unresolved'), 'AI recap did not persist.');
  await page.screenshot({ path: 'design/previews/story-memory.png', scale: 'css' });
  await page.evaluate(() => {
    const state = JSON.parse(localStorage.getItem('blackstone-campaign-v1'));
    state.mode = 'complete'; state.storyFlags.partyDefeated = true; state.party.forEach(hero => { hero.hp = 0; });
    localStorage.setItem('blackstone-campaign-v1', JSON.stringify(state));
  });
  await page.reload();
  await page.getByRole('button', { name: 'Review saved scenes', exact: true }).click();
  await savedRow.getByRole('button', { name: 'Resume scene', exact: true }).click();
  await page.waitForFunction(() => !JSON.parse(localStorage.getItem('blackstone-campaign-v1')).storyFlags.partyDefeated);
  assert(await page.locator('.checkpoint-row').filter({ hasText: 'Expedition ended' }).count() > 0, 'Defeat checkpoint was not retained after rewind.');
  await page.getByRole('button', { name: 'New campaign', exact: true }).click();
  await page.locator('#hero-name').fill('Another expedition');
  await page.locator('[data-start-skill]').nth(0).check(); await page.locator('[data-start-skill]').nth(2).check();
  await page.getByRole('button', { name: 'Add hero', exact: true }).click();
  await page.getByRole('button', { name: 'Begin expedition', exact: true }).click();
  await page.locator('#enter-dungeon').click();
  await page.locator('[data-inspector="story"]').click();
  assert(await savedRow.count() === 1, 'Starting another expedition hid earlier highlights.');
  await page.goto('http://127.0.0.1:5173/workshop.html?view=costs');
  assert((await page.locator('#story-growth-comparison').textContent()).includes('$13.7040'), 'Long-story calculation is wrong.');
  await page.locator('#cost-history').selectOption('rolling');
  assert((await page.locator('#cost-results').textContent()).includes('$0.0428'), 'Rolling-memory estimate is wrong.');
  await page.locator('#cost-summary-every').selectOption('10');
  assert((await page.locator('#cost-results').textContent()).includes('$0.0502'), 'AI recap overhead is missing.');
  await page.setViewportSize({ width: 390, height: 844 });
  assert(!await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), 'Memory cost page overflows on mobile.');
  await page.unroute('**/api/status'); await page.unroute('**/api/dm');
  return { checkpoints: 'full state, defeat recovery and cross-campaign history passed', longStory: '1000 events bounded in actual prompt', aiRecap: 'one manual request and persisted', growingCost: 'passed', mobile: 'passed', paidCalls: 0 };
}
